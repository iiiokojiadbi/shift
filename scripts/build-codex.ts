// Build the installed plugin from this checkout. The marketplace copies only the plugin directory.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dir, '..')
const output = resolve(root, 'adapters/codex/plugin/runtime.js')
const build = await Bun.build({
  entrypoints: [resolve(root, 'adapters/codex/native.ts')],
  target: 'bun',
  define: { SHIFT_MARKETPLACE: 'true' },
  plugins: [
    {
      name: 'shared node store',
      setup(builder) {
        builder.onResolve({ filter: /^\.\/core\/index$/ }, args =>
          args.importer === resolve(root, 'adapters/npm/store.ts') ? { path: resolve(root, 'core/src/index.ts') } : undefined,
        )
      },
    },
  ],
})
const [entry] = build.outputs
if (!build.success || !entry || build.outputs.length !== 1)
  throw new Error(build.logs.map(String).join('\n') || 'Expected one plugin entry.')
const text = `// Generated by scripts/build-codex.ts from the adapter and core.\n${await entry.text()}`
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== text) throw new Error('The installed plugin is stale. Run bun run build:codex.')
} else await writeFile(output, text)
